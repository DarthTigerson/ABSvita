#!/usr/bin/env python3
"""Writes src/ui/font_metrics.h: per-glyph ink side bearings (ASCII 32..126) and
cap height for the bundled Manrope weights, in font units. Used to centre text
on its ink box rather than its advance box. Needs fontTools."""
from fontTools.ttLib import TTFont

out = ["/* Generated by tools/gen_font_metrics.py — do not edit. */",
       "#ifndef ABSVITA_FONT_METRICS_H", "#define ABSVITA_FONT_METRICS_H", ""]
for w in ("500", "700"):
    f = TTFont("assets/fonts/Manrope-%s.ttf" % w)
    upm = f["head"].unitsPerEm
    cmap = f.getBestCmap()
    hmtx = f["hmtx"]
    glyf = f["glyf"]
    lsb, rsb = [], []
    for c in range(32, 127):
        g = cmap.get(c)
        adv, l = hmtx[g]
        gl = glyf[g]
        if getattr(gl, "numberOfContours", 0) == 0:
            lsb.append(0); rsb.append(0)
            continue
        lsb.append(gl.xMin)
        rsb.append(adv - gl.xMax)
    out.append("#define FM%s_UPM %d" % (w, upm))
    out.append("#define FM%s_CAP %d" % (w, f["OS/2"].sCapHeight))
    out.append("static const short fm%s_lsb[95] = {%s};" % (w, ",".join(map(str, lsb))))
    out.append("static const short fm%s_rsb[95] = {%s};" % (w, ",".join(map(str, rsb))))
    out.append("")
out += ["#endif", ""]
open("src/ui/font_metrics.h", "w").write("\n".join(out))
print("wrote src/ui/font_metrics.h")
